"""Writes build/recomp/MegaHaloGame.toml, the XenonRecomp config: the register
save and restore helpers and setjmp/longjmp found by their PDB names, and
every function boundary from config/functions.csv.

    python tools/recomp_config.py

Paths in the TOML are relative to build/recomp/: the decrypted XEX in orig/
(tools/xex.py --decrypted; XenonRecomp knows only the retail key), output into
build/recomp/ppc/ (created here), jump tables from recomp/switch_tables.toml.
"""
import argparse

import inventory
import paths
from pdbfile import IMAGE_BASE, Pdb

# XenonRecomp key -> PDB public name, and the bytes the helper block spans
HELPERS = {
    'savegprlr_14_address': ('__savegprlr_14', 18 * 4 + 8),
    'restgprlr_14_address': ('__restgprlr_14', 18 * 4 + 12),
    'savefpr_14_address': ('__savefpr_14', 18 * 4 + 4),
    'restfpr_14_address': ('__restfpr_14', 18 * 4 + 4),
    'savevmx_14_address': ('__savevmx_14', 18 * 8 + 4),
    'restvmx_14_address': ('__restvmx_14', 18 * 8 + 4),
    'savevmx_64_address': ('__savevmx_64', 64 * 8 + 4),
    'restvmx_64_address': ('__restvmx_64', 64 * 8 + 4),
    'setjmp_address': ('setjmp', 0),
    'longjmp_address': ('longjmp', 0),
}
TOML = paths.BUILD / 'recomp' / 'MegaHaloGame.toml'


def helpers(pdb):
    """XenonRecomp key -> VA of each helper, by its PDB public name."""
    by_name = {}
    for rva, name in pdb.publics().items():
        by_name.setdefault(name, rva)
    out = {}
    for key, (name, _span) in HELPERS.items():
        if name not in by_name:
            raise SystemExit(f'helper {name} not in the PDB')
        out[key] = IMAGE_BASE + by_name[name]
    return out


def functions(rows, helper_vas):
    """(address, size) of each function with code, leaving out the helper
    blocks, which XenonRecomp lays out itself."""
    spans = [(va, va + max(HELPERS[k][1], 1)) for k, va in helper_vas.items() if HELPERS[k][1]]
    out = []
    for r in rows:
        va, size = int(r['address'], 16), int(r['size'])
        if size and not any(lo <= va < hi for lo, hi in spans):
            out.append((va, size))
    return out


def render(helper_vas, funcs):
    lines = ['# Generated by tools/recomp_config.py from the PDB; do not edit.', '[main]',
             'file_path = "../../orig/MegaHaloGame.dec.xex"',
             'out_directory_path = "ppc"',
             'switch_table_file_path = "../../recomp/switch_tables.toml"', '']
    lines += [f'{k} = 0x{v:08X}' for k, v in helper_vas.items()]
    lines += ['', 'invalid_instructions = [', '    { data = 0x00000000, size = 4 },  # padding', ']', '',
              'functions = [']
    lines += [f'    {{ address = 0x{va:08X}, size = 0x{size:X} }},' for va, size in funcs]
    lines += [']', '']
    return '\n'.join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description='Write the XenonRecomp config from the PDB.')
    ap.add_argument('--pdb', default=None)
    args = ap.parse_args(argv)
    helper_vas = helpers(Pdb(args.pdb or paths.pdb()))
    funcs = functions(inventory.read_csv(paths.CONFIG / 'functions.csv'), helper_vas)
    (TOML.parent / 'ppc').mkdir(parents=True, exist_ok=True)
    TOML.write_text(render(helper_vas, funcs), encoding='utf-8', newline='\n')
    print(f'wrote {TOML}: {len(funcs)} functions')


if __name__ == '__main__':
    main()

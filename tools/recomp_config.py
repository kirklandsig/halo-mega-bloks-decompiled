"""Writes the ReXGlue codegen inputs into $HAGGAR_BUILD_DIR/recomp/ (default
build/recomp/): haggar_manifest.toml, the project manifest that
`rexglue codegen` reads, and functions.toml, every function boundary from
config/functions.csv plus setjmp/longjmp found by their PDB names.

    python tools/recomp_config.py

The manifest includes functions.toml and the committed jump tables
(recomp/switch_tables.toml, tools/switch_tables.py). Paths in it are relative
to the manifest. ReXGlue reads the devkit-signed XEX itself; the generated
C++ goes to recomp/generated/ next to the manifest.
"""
import argparse
import os

import inventory
import paths
from pdbfile import IMAGE_BASE, Pdb

# PDB public name -> the bytes the helper block spans. ReXGlue finds the
# register save and restore helpers by their byte patterns, so their blocks
# are left out of the function list.
HELPERS = {
    '__savegprlr_14': 18 * 4 + 8,
    '__restgprlr_14': 18 * 4 + 12,
    '__savefpr_14': 18 * 4 + 4,
    '__restfpr_14': 18 * 4 + 4,
    '__savevmx_14': 18 * 8 + 4,
    '__restvmx_14': 18 * 8 + 4,
    '__savevmx_64': 64 * 8 + 4,
    '__restvmx_64': 64 * 8 + 4,
    'setjmp': 0,
    'longjmp': 0,
}
SDK_VERSION = '0.10.0'


def recomp_dir():
    return paths.BUILD / 'recomp'


def helpers(pdb):
    """PDB name -> VA of each helper."""
    by_name = {}
    for rva, name in pdb.publics().items():
        by_name.setdefault(name, rva)
    out = {}
    for name in HELPERS:
        if name not in by_name:
            raise SystemExit(f'helper {name} not in the PDB')
        out[name] = IMAGE_BASE + by_name[name]
    return out


def functions(rows, helper_vas, thunks=()):
    """(address, size) of each function with code, leaving out the helper
    blocks and the import thunks. ReXGlue names a thunk __imp__<export>, and a
    [functions] entry at the same address would rename it sub_<address>."""
    spans = [(va, va + HELPERS[k]) for k, va in helper_vas.items() if HELPERS[k]]
    thunks = set(thunks)
    out = []
    for r in rows:
        va, size = int(r['address'], 16), int(r['size'])
        if size and va not in thunks and not any(lo <= va < hi for lo, hi in spans):
            out.append((va, size))
    return out


def render_functions(helper_vas, funcs):
    lines = ['# Generated by tools/recomp_config.py from the PDB; do not edit.',
             f'setjmp_address = 0x{helper_vas["setjmp"]:08X}',
             f'longjmp_address = 0x{helper_vas["longjmp"]:08X}', '', '[functions]']
    lines += [f'0x{va:08X} = {{ size = 0x{size:X} }}' for va, size in funcs]
    return '\n'.join(lines) + '\n'


def _rel(target, base):
    try:
        return os.path.relpath(target, base).replace('\\', '/')
    except ValueError:  # another drive
        return str(target).replace('\\', '/')


def render_manifest(base, xex, switch_tables):
    return '\n'.join([
        '# Generated by tools/recomp_config.py; do not edit.',
        '[project]',
        'name = "haggar"',
        f'sdk_version = "{SDK_VERSION}"',
        f'game_root = "{_rel(xex.parent, base)}"',
        '',
        '[entrypoint]',
        f'file_path = "{_rel(xex, base)}"',
        'out_directory_path = "generated"',
        f'includes = ["functions.toml", "{_rel(switch_tables, base)}"]',
        '',
    ])


def main(argv=None):
    ap = argparse.ArgumentParser(description='Write the ReXGlue codegen inputs from the PDB.')
    ap.add_argument('--pdb', default=None)
    args = ap.parse_args(argv)
    helper_vas = helpers(Pdb(args.pdb or paths.pdb()))
    thunks = [int(r['thunk'], 16) for r in inventory.read_csv(paths.CONFIG / 'imports.csv')]
    funcs = functions(inventory.read_csv(paths.CONFIG / 'functions.csv'), helper_vas, thunks)
    out = recomp_dir()
    out.mkdir(parents=True, exist_ok=True)
    (out / 'functions.toml').write_text(render_functions(helper_vas, funcs), encoding='utf-8', newline='\n')
    manifest = render_manifest(out, paths.xex().resolve(), paths.ROOT / 'recomp' / 'switch_tables.toml')
    (out / 'haggar_manifest.toml').write_text(manifest, encoding='utf-8', newline='\n')
    print(f'wrote {out}: haggar_manifest.toml, functions.toml ({len(funcs)} functions)')


if __name__ == '__main__':
    main()
